"""Rebuild ``src/duplio/assets/logo_data.py`` (the pixel-art mark) from the icon, keeping its transparency.

    python tools/make_logo.py            # needs Pillow

The mark is the icon sampled to 38x40 pixels. Each pixel keeps its own opacity and the colour of the light itself
(never blended with a background), so it can be laid on any background, dark or light, without a pale fringe.
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "duplio-icon-original.png"
TARGET = ROOT / "src" / "duplio" / "assets" / "logo_data.py"
WIDTH, HEIGHT = 38, 40
FAINT = 10  # opacity (0-255) below which a pixel is left out altogether


def sample() -> list[list[tuple[int, int, int, int]]]:
    icon = Image.open(SOURCE).convert("RGBA")
    box = icon.getchannel("A").point(lambda a: 255 if a > 40 else 0).getbbox()  # ignore the faintest specks when framing
    assert box is not None, "the icon is empty"
    icon = icon.crop(box)
    # Average in premultiplied space so a transparent pixel's (meaningless) colour never leaks into its neighbours.
    pixels = icon.load()
    pre = Image.new("RGBA", icon.size)
    out = pre.load()
    for y in range(icon.height):
        for x in range(icon.width):
            r, g, b, a = pixels[x, y]
            out[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
    small = pre.resize((WIDTH, HEIGHT), Image.Resampling.BOX)
    grid = []
    for y in range(HEIGHT):
        row = []
        for x in range(WIDTH):
            r, g, b, a = small.getpixel((x, y))
            if a < FAINT:
                row.append((0, 0, 0, 0))
            else:
                row.append((min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a), a))  # un-premultiply
        grid.append(row)
    return grid


def main() -> int:
    grid = sample()
    lines = [
        '"""The Duplio mark as pixels. Generated by tools/make_logo.py from assets/duplio-icon-original.png; do not edit by hand.',
        "",
        "Each row is 38 pixels of 8 hex digits: red, green, blue, opacity. The colour is the light itself, not blended with a",
        'background (opacity 00 = nothing there), so the mark can be laid on a dark or a light background alike."""',
        "",
        "from __future__ import annotations",
        "",
        "ROWS = (",
    ]
    for row in grid:
        lines.append("    '" + "".join(f"{r:02x}{g:02x}{b:02x}{a:02x}" for r, g, b, a in row) + "',")
    lines.append(")")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {WIDTH}x{HEIGHT}, {sum(1 for row in grid for p in row if p[3])} pixels used")
    return 0


if __name__ == "__main__":
    sys.exit(main())
